// Shared helpers/constants for the auth endpoints.

import type { User } from "@supabase/supabase-js";
import { env } from "../../config/env";
import { isAuthOutage } from "../../lib/auth-outage";
import { retryOnNetworkError } from "../../lib/db-retry";
import { emailLikePattern } from "../../lib/email";
import { APP_ROLES, type AppRole } from "../../lib/roles";
import { supabaseAdmin } from "../../lib/supabase";
import { rejectedTokenMessage } from "../../lib/token-issuer";

// Roles a brand-new OAuth user may choose when their profile row is created
// (one list for the whole server: src/lib/roles.ts).
export const VALID_ROLES = APP_ROLES;
export type ServerRole = AppRole;

// Maps each role to the table(s) holding its role-specific row. Every role now
// has a profile table (rider/agent existed; merchant/customer added in
// migration 00018). The display ID column on each is DB-generated (sequence-
// backed default), so inserting only `user_id` is enough.
const ROLE_PROFILE_TABLE: Record<ServerRole, string> = {
  rider: "rider_profiles",
  agent: "agent_profiles",
  merchant: "merchant_profiles",
  customer: "customer_profiles",
};

/**
 * Idempotently create the role-specific profile row(s) for a user. Safe to call
 * for an existing user (the per-role `UNIQUE(user_id)` makes a duplicate insert
 * a no-op we swallow), so it doubles as a backfill for accounts created before
 * their role table existed. Agents also get an empty `agent_shops` row.
 *
 * Single source of truth for POST /auth/role, /auth/google, /auth/apple and
 * the phone OTP flow (/auth/otp/verify, /auth/otp/register) —
 * keep role-creation logic here, not duplicated per route.
 */
export async function ensureRoleProfile(
  userId: string,
  role: ServerRole,
): Promise<void> {
  if (role === "agent") {
    // The agent's SHOP is a separate row, created alongside the profile — a
    // blank primary placeholder the agent fills in (POST /agents/shops).
    // Agents may own several shops, so check before inserting.
    const { data: shops } = await supabaseAdmin
      .from("agent_shops")
      .select("id")
      .eq("user_id", userId)
      .limit(1);
    if (!shops?.length) {
      await supabaseAdmin.from("agent_shops").insert({
        user_id: userId,
        shop_name: "",
        open_time: "08:00",
        close_time: "20:00",
        status: "closed",
        latitude: 0,
        longitude: 0,
        rating: 0,
        is_primary: true,
      });
    }
  }

  // Display ID is auto-generated by the DB; insert only the FK. Upsert with
  // ignoreDuplicates so a re-run (backfill) never errors on the unique user_id
  // — which also makes it safe to replay through a network blip.
  await retryOnNetworkError(() =>
    supabaseAdmin
      .from(ROLE_PROFILE_TABLE[role])
      .upsert({ user_id: userId }, { onConflict: "user_id", ignoreDuplicates: true })
  );
}

/**
 * The Supabase user behind the request's bearer token, for sign-up routes that
 * run before the `public.users` row exists (so not behind the `auth`
 * middleware). 503, not 401, when Supabase can't be reached: the app signs the
 * user out on a 401, which would throw away a half-finished sign-up.
 */
export async function getBearerUser(
  header: string | undefined,
): Promise<{ user: User } | { status: 401 | 503; error: string }> {
  if (!header?.startsWith("Bearer ")) {
    return { status: 401, error: "Missing or invalid authorization header" };
  }

  const token = header.slice(7);
  let auth = await supabaseAdmin.auth.getUser(token);
  // One retry: a network blip reaching Supabase Auth is common in dev.
  if (isAuthOutage(auth.error)) auth = await supabaseAdmin.auth.getUser(token);

  if (isAuthOutage(auth.error)) {
    return { status: 503, error: "Service temporarily unavailable, please retry" };
  }
  if (auth.error || !auth.data.user) {
    return { status: 401, error: rejectedTokenMessage(token, env.SUPABASE_URL) };
  }
  return { user: auth.data.user };
}

/**
 * Whether another account's profile already uses `email` (case-insensitive).
 * Throws when Supabase can't answer — callers turn that into a 503.
 */
export async function isEmailTaken(email: string, exceptUserId: string): Promise<boolean> {
  const { data, error } = await supabaseAdmin
    .from("users")
    .select("id")
    .ilike("email", emailLikePattern(email))
    .neq("id", exceptUserId)
    .limit(1);
  if (error) throw error;
  return data.length > 0;
}

import { supabaseAdmin } from "../../lib/supabase";
import { bearer, createRoute, errorResponses, json, router } from "../../openapi";
import { RiderProfileResponse, updateRiderProfileSchema } from "../../validators/riders";

const app = router();

// ─── Update rider profile ────────────────────────────────────────────
const route = createRoute({
  method: "patch",
  path: "/profile",
  operationId: "updateRiderProfile",
  tags: ["riders"],
  security: bearer,
  request: { body: { ...json(updateRiderProfileSchema), required: true } },
  responses: {
    200: json(RiderProfileResponse),
    400: errorResponses[400],
    401: errorResponses[401],
    403: errorResponses[403],
    404: errorResponses[404],
  },
});

app.openapi(route, async (c) => {
  const user = c.get("user");
  const body = c.req.valid("json");

  // Create-if-missing: OAuth users who picked "rider" never went through
  // POST /auth/role, so they may have no rider_profiles row yet. Heal it here.
  const { data: existing } = await supabaseAdmin
    .from("rider_profiles")
    .select("id")
    .eq("user_id", user.id)
    .single();

  let result;
  if (existing) {
    result = await supabaseAdmin
      .from("rider_profiles")
      .update(body)
      .eq("user_id", user.id)
      .select()
      .single();
  } else {
    // rider_id is auto-generated by the DB (sequence-backed default).
    result = await supabaseAdmin
      .from("rider_profiles")
      .insert({ ...body, user_id: user.id })
      .select()
      .single();
  }

  if (result.error || !result.data) {
    return c.json(
      { error: result.error?.message ?? "Could not save rider profile" },
      400,
    );
  }

  return c.json({ profile: result.data }, 200);
});

export default app;

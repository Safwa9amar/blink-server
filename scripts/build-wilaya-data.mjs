// Regenerates src/lib/geo/wilaya-data.ts: simplified boundary polygons of the
// 58 wilayas (Douglas-Peucker, 1e-3 deg grid, delta-encoded).
// Source: https://github.com/samdace/Algeria-Cities-GeoJson (MIT), via
// https://github.com/namrouche993/algeria-wilayas-geojson v58/algeria-cities.geojson.
// Usage: node scripts/build-wilaya-data.mjs [tolerance_deg=0.006]
import { writeFileSync } from "node:fs";

const URL_ = "https://raw.githubusercontent.com/namrouche993/algeria-wilayas-geojson/main/v58/algeria-cities.geojson";
const TOL = Number(process.argv[2] ?? 0.006);
const norm = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toUpperCase().replace(/[^A-Z]/g, "");

// Wilaya codes → names (algeria-locations order, codes "1".."58").
const NAMES = [
  "Adrar","Chlef","Laghouat","Oum El Bouaghi","Batna","Béjaïa","Biskra","Béchar","Blida","Bouira",
  "Tamanrasset","Tébessa","Tlemcen","Tiaret","Tizi Ouzou","Alger","Djelfa","Jijel","Sétif","Saïda",
  "Skikda","Sidi Bel Abbès","Annaba","Guelma","Constantine","Médéa","Mostaganem","M'Sila","Mascara","Ouargla",
  "Oran","El Bayadh","Illizi","Bordj Bou Arréridj","Boumerdès","El Tarf","Tindouf","Tissemsilt","El Oued","Khenchela",
  "Souk Ahras","Tipaza","Mila","Aïn Defla","Naâma","Aïn Témouchent","Ghardaïa","Relizane","Timimoun","Bordj Badji Mokhtar",
  "Ouled Djellal","Béni Abbès","In Salah","In Guezzam","Touggourt","Djanet","El M'Ghair","El Meniaa",
];
const code = new Map(NAMES.map((n, i) => [norm(n), String(i + 1)]));
code.set("MEGHAIER", "57");
code.set("MENIAA", "58");

function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let max = 0, idx = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = dx * dx + dy * dy;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      let d;
      if (len === 0) d = Math.hypot(px - ax, py - ay);
      else {
        const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len));
        d = Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
      }
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const fc = await (await fetch(URL_)).json();
const out = {};
for (const f of fc.features) {
  const c = code.get(norm(f.properties.nam));
  if (!c) throw new Error(`unmapped ${f.properties.nam}`);
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  // Outer rings only (holes are exclaves of other wilayas, matched first-come).
  out[c] = polys.map((p) => {
    const ring = dp(p[0], TOL).map(([x, y]) => [Math.round(x * 1000), Math.round(y * 1000)]);
    const flat = [];
    let px = 0, py = 0;
    for (const [x, y] of ring) { flat.push(x - px, y - py); px = x; py = y; }
    return flat;
  });
}
const body = JSON.stringify(out);
writeFileSync(
  new URL("../src/lib/geo/wilaya-data.ts", import.meta.url),
  `// GENERATED by scripts/build-wilaya-data.mjs — do not edit.
// Simplified outer boundaries of the 58 wilayas (post-2019 layout).
// Source: samdace/Algeria-Cities-GeoJson (MIT, https://github.com/samdace/Algeria-Cities-GeoJson),
// redistributed by namrouche993/algeria-wilayas-geojson (v58, MIT). Simplified with
// Douglas-Peucker (tolerance ${TOL} deg ≈ ${Math.round(TOL * 111)} m), quantised to 1e-3 deg.
// Format: code → polygons → flat [x0, y0, dx1, dy1, …] in 1e-3 deg (x = lng, y = lat), delta-encoded.
export const WILAYA_POLYGONS: Record<string, number[][]> = ${body};
`
);
